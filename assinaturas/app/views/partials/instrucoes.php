<div class="tabs" data-tabs>
    <div class="tab-list" role="tablist" aria-label="Cliente de e-mail">
        <button type="button" role="tab" aria-selected="true" data-tab="gmail">Gmail</button>
        <button type="button" role="tab" aria-selected="false" data-tab="outlook">Outlook</button>
        <button type="button" role="tab" aria-selected="false" data-tab="apple">Apple Mail</button>
    </div>

    <div role="tabpanel" data-tab-panel="gmail">
        <ol class="steps">
            <li>Clique em <strong>Copiar assinatura</strong> nesta página.</li>
            <li>Abra o Gmail no computador, clique na engrenagem no canto superior direito e depois em <strong>Ver todas as configurações</strong>.</li>
            <li>Na aba <strong>Geral</strong>, desça até <strong>Assinatura</strong> e clique em <strong>Criar nova</strong>. Dê um nome para ela.</li>
            <li>Clique dentro da caixa de texto da assinatura e cole com <kbd>Ctrl</kbd> + <kbd>V</kbd> (no Mac, <kbd>Cmd</kbd> + <kbd>V</kbd>).</li>
            <li>Em <strong>Padrões de assinatura</strong>, escolha a assinatura para novos e-mails e para respostas.</li>
            <li>Vá até o fim da página e clique em <strong>Salvar alterações</strong>.</li>
        </ol>
        <p class="note">O Gmail aceita assinaturas de até 10.000 caracteres. O editor avisa quando a sua passa desse tamanho. No aplicativo do Gmail para celular, a assinatura do computador só aparece se a opção "Assinatura para dispositivos móveis" estiver desligada no aplicativo.</p>
    </div>

    <div role="tabpanel" data-tab-panel="outlook" hidden>
        <h4>Novo Outlook e Outlook na Web</h4>
        <ol class="steps">
            <li>Clique em <strong>Copiar assinatura</strong> nesta página.</li>
            <li>No Outlook, clique na engrenagem e vá em <strong>Contas</strong> e depois em <strong>Assinaturas</strong>.</li>
            <li>Clique em <strong>Nova assinatura</strong>, dê um nome e cole na caixa de edição com <kbd>Ctrl</kbd> + <kbd>V</kbd>.</li>
            <li>Escolha a assinatura como padrão para novas mensagens e para respostas e clique em <strong>Salvar</strong>.</li>
        </ol>
        <h4>Outlook clássico para Windows</h4>
        <ol class="steps">
            <li>Clique em <strong>Copiar assinatura</strong> nesta página.</li>
            <li>No Outlook, abra <strong>Arquivo</strong>, depois <strong>Opções</strong>, <strong>Email</strong> e clique em <strong>Assinaturas</strong>.</li>
            <li>Clique em <strong>Novo</strong>, dê um nome e cole na caixa <strong>Editar assinatura</strong>. Se aparecer a opção de colagem, escolha <strong>Manter formatação original</strong>.</li>
            <li>Escolha a assinatura para novas mensagens e para respostas e clique em <strong>OK</strong>.</li>
        </ol>
        <h4>Outlook para Mac</h4>
        <ol class="steps">
            <li>Clique em <strong>Copiar assinatura</strong> nesta página.</li>
            <li>No menu <strong>Outlook</strong>, abra <strong>Configurações</strong> e depois <strong>Assinaturas</strong>.</li>
            <li>Clique no botão <strong>+</strong>, cole a assinatura e salve.</li>
        </ol>
        <p class="note">O Outlook clássico guarda uma cópia das imagens no momento da instalação. Se o logotipo ou o banner mudarem, instale a assinatura de novo. Nele a foto redonda só aparece redonda quando foi enviada para a plataforma, porque ele ignora cantos arredondados.</p>
    </div>

    <div role="tabpanel" data-tab-panel="apple" hidden>
        <h4>Mail no Mac</h4>
        <ol class="steps">
            <li>Clique em <strong>Copiar assinatura</strong> nesta página, usando o Safari ou o Chrome.</li>
            <li>No Mail, abra o menu <strong>Mail</strong>, depois <strong>Ajustes</strong> e a aba <strong>Assinaturas</strong>.</li>
            <li>Selecione a conta de e-mail na coluna da esquerda e clique no botão <strong>+</strong>. Dê um nome.</li>
            <li>Desmarque <strong>Sempre usar minha fonte padrão</strong>.</li>
            <li>Clique na área da direita e cole com <kbd>Cmd</kbd> + <kbd>V</kbd>.</li>
            <li>Em <strong>Escolher assinatura</strong>, selecione a nova assinatura e feche a janela.</li>
        </ol>
        <h4>Mail no iPhone e no iPad</h4>
        <ol class="steps">
            <li>Abra esta página no próprio aparelho e toque em <strong>Copiar assinatura</strong>.</li>
            <li>Abra <strong>Ajustes</strong>, depois <strong>Apps</strong>, <strong>Mail</strong> e <strong>Assinatura</strong>.</li>
            <li>Apague o texto atual, toque e segure na caixa e escolha <strong>Colar</strong>.</li>
            <li>Agite o aparelho e toque em <strong>Desfazer</strong> quando aparecer "Desfazer alteração de atributos". Isso devolve as cores e o formato originais.</li>
        </ol>
        <p class="note">Na janela de ajustes do Mail as imagens podem aparecer como espaços vazios. Elas aparecem normalmente ao escrever uma nova mensagem. Se não aparecerem para você, confira em Ajustes, Privacidade, se a opção de bloquear conteúdo remoto está desligada.</p>
    </div>
</div>
